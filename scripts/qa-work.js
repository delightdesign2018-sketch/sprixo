import { chromium } from 'playwright';
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
await page.goto('http://localhost:5173', { waitUntil: 'networkidle' });
await page.waitForTimeout(2500);
await page.locator('#work').scrollIntoViewIfNeeded();
await page.waitForTimeout(1200);
await page.screenshot({ path: 'qa-work-desktop.png' });
await page.setViewportSize({ width: 768, height: 1024 });
await page.waitForTimeout(800);
await page.locator('#work').scrollIntoViewIfNeeded();
await page.waitForTimeout(800);
await page.screenshot({ path: 'qa-work-tablet.png' });
await page.setViewportSize({ width: 390, height: 844 });
await page.waitForTimeout(800);
await page.locator('#work').scrollIntoViewIfNeeded();
await page.waitForTimeout(800);
await page.screenshot({ path: 'qa-work-mobile.png' });
await page.goto('http://localhost:5173/work/voltexa/', { waitUntil: 'networkidle' });
await page.waitForTimeout(600);
await page.screenshot({ path: 'qa-project.png' });
await browser.close();
console.log('done');
